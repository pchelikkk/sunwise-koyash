async def seed_products(database: AsyncDatabase[Any]) -> None:
    collection = database["products"]

    for product in PRODUCTS:
        await collection.update_one(
            {"external_id": product["external_id"]},
            {
                "$set": {
                    **product,
                    "updated_at": utc_now(),
                },
                "$setOnInsert": {
                    "created_at": utc_now(),
                },
            },
            upsert=True,
        )
